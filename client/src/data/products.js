// ============================================================
// PRODUCT IMAGE LOADER
// ============================================================
//
// All product images are stored inside:
//
// src/images/products/
//
// Vite automatically loads all JPG, JPEG, PNG and WEBP images
// from this folder.
//
// Example:
// src/images/products/moringa-1.jpg
// becomes:
// /src/images/products/moringa-1.jpg
//
// ============================================================

const imageFiles = import.meta.glob(
  "../images/products/*.{jpg,jpeg,png,webp,JPG,JPEG,PNG,WEBP}",
  {
    eager: true,
    import: "default",
  }
);


// ============================================================
// IMAGE HELPER
// ============================================================
//
// Instead of writing:
//
// "/images/products/moringa-1.jpg"
//
// we write:
//
// getImage("moringa-1")
//
// ============================================================

const getImage = (name) => {
  const extensions = [
    "jpg",
    "jpeg",
    "png",
    "webp",
    "JPG",
    "JPEG",
    "PNG",
    "WEBP",
  ];

  for (const extension of extensions) {
    const path = `../images/products/${name}.${extension}`;

    if (imageFiles[path]) {
      return imageFiles[path];
    }
  }

  console.warn(`Product image not found: ${name}`);

  return "";
};


